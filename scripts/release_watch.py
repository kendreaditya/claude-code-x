#!/usr/bin/env python3
"""release-watch helper for the daily GitHub Action.

Subcommands:
  check                          print whether the latest published CC version is
                                 newer than the last validated one (GH outputs)
  report <result.json>...        merge per-platform `ccx validate-all --json`
                                 results into COMPATIBILITY.md, update
                                 compat/validated.json, and list patches that
                                 broke (so CI can archive them)

This NEVER publishes the patched binary — only patch definitions + the report.
Redistributing a modified Anthropic binary would breach Anthropic's ToS/copyright.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
COMPAT = ROOT / "compat"
VALIDATED = COMPAT / "validated.json"

from ccx import release  # noqa: E402


def _gh_output(**kw):
    out = os.environ.get("GITHUB_OUTPUT")
    line = "\n".join(f"{k}={v}" for k, v in kw.items())
    if out:
        with open(out, "a") as f:
            f.write(line + "\n")
    print(line)


def cmd_check() -> int:
    latest = release.latest_version()
    last = ""
    if VALIDATED.exists():
        last = json.loads(VALIDATED.read_text()).get("version", "")
    _gh_output(version=latest, last_validated=last,
               new=str(latest != last).lower())
    return 0


def cmd_report(result_files: list[str]) -> int:
    COMPAT.mkdir(parents=True, exist_ok=True)
    per_platform = {}
    version = None
    for fp in result_files:
        doc = json.loads(Path(fp).read_text())
        version = doc.get("version", version)
        per_platform[doc["container"]] = {r["id"]: r for r in doc["results"]}

    # union of all patch ids
    ids = sorted({pid for plat in per_platform.values() for pid in plat})

    def cell(r):
        if r is None:
            return "—"
        if r.get("applies") and r.get("launch_ok") in (True, None):
            return "✅"
        return "❌"

    # a patch is "broken" if it fails to apply on every platform where it's relevant
    broken = []
    for pid in ids:
        verdicts = [per_platform[c].get(pid) for c in per_platform]
        relevant = [v for v in verdicts if v and v.get("reason") != "version/container incompatible"]
        if relevant and all(not (v.get("applies") and v.get("launch_ok") in (True, None))
                            for v in relevant):
            broken.append(pid)

    # write COMPATIBILITY.md
    cols = sorted(per_platform)
    lines = [f"# Patch compatibility — Claude Code {version}", "",
             "Auto-generated by the release-watch GitHub Action. ✅ = applies + launches,",
             "❌ = failed, — = N/A for that platform. The patched binary is **not** published",
             "(see CREDITS.md / GOAL.md — redistributing a modified Anthropic binary is not done).",
             "",
             "| patch | " + " | ".join(cols) + " |",
             "|---|" + "|".join(["---"] * len(cols)) + "|"]
    for pid in ids:
        row = [cell(per_platform[c].get(pid)) for c in cols]
        lines.append(f"| `{pid}` | " + " | ".join(row) + " |")
    if broken:
        lines += ["", "## Broke on this version", ""]
        lines += [f"- `{b}` — moved to `registry/_archived/` by CI" for b in broken]
    (COMPAT / "COMPATIBILITY.md").write_text("\n".join(lines) + "\n")

    VALIDATED.write_text(json.dumps({"version": version, "platforms": list(per_platform)},
                                    indent=2) + "\n")
    _gh_output(version=version or "", broken=",".join(broken),
               has_broken=str(bool(broken)).lower())
    print(f"report written for {version}; broken={broken}")
    return 0


def main(argv) -> int:
    if not argv:
        print(__doc__)
        return 2
    if argv[0] == "check":
        return cmd_check()
    if argv[0] == "report":
        return cmd_report(argv[1:])
    if argv[0] == "download":
        version, plat, dest = argv[1], argv[2], Path(argv[3])
        release.download_binary(version, dest, plat)
        print(f"downloaded {version}/{plat} -> {dest} ({dest.stat().st_size:,} bytes)")
        return 0
    print(f"unknown subcommand: {argv[0]}")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
